-- ActivityDay: executar no Supabase SQL Editor uma única vez.
-- Esta tabela permite que cada utilizador veja e altere apenas as suas próprias actividades.
create table if not exists public.activities (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 120),
  category text not null check (category in ('Pessoais','Familiares','Educacionais','Espirituais','Laborais','Saúde','Financeiras','Casa','Sociais','Lazer')),
  frequency text not null default 'Diária' check (frequency in ('Diária','Semanal','Mensal')),
  done boolean not null default false,
  due_date date,
  reminder_time time,
  priority text not null default 'Normal' check (priority in ('Baixa','Normal','Alta')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists activities_user_due_date_idx on public.activities(user_id, due_date);
create index if not exists activities_user_created_at_idx on public.activities(user_id, created_at desc);

alter table public.activities enable row level security;

-- Remove broad anonymous access; authenticated users receive only row-level access to their own data.
revoke all on table public.activities from anon;
grant select, insert, update, delete on table public.activities to authenticated;
grant usage, select on sequence public.activities_id_seq to authenticated;

drop policy if exists "Users can read own activities" on public.activities;
create policy "Users can read own activities" on public.activities
for select to authenticated using ((select auth.uid()) = user_id);

drop policy if exists "Users can insert own activities" on public.activities;
create policy "Users can insert own activities" on public.activities
for insert to authenticated with check ((select auth.uid()) = user_id);

drop policy if exists "Users can update own activities" on public.activities;
create policy "Users can update own activities" on public.activities
for update to authenticated using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete own activities" on public.activities;
create policy "Users can delete own activities" on public.activities
for delete to authenticated using ((select auth.uid()) = user_id);

create or replace function public.set_activity_updated_at()
returns trigger language plpgsql set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_activities_updated_at on public.activities;
create trigger set_activities_updated_at before update on public.activities
for each row execute function public.set_activity_updated_at();
