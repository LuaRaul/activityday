create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null unique,
  subscription jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists push_subscriptions_user_id_idx on public.push_subscriptions(user_id);
alter table public.push_subscriptions enable row level security;
revoke all on table public.push_subscriptions from anon, authenticated;
-- As subscrições são geridas exclusivamente por funções Netlify com a service role.

create table if not exists public.push_deliveries (
  id bigint generated by default as identity primary key,
  activity_id bigint not null references public.activities(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  due_date date not null,
  reminder_time time not null,
  sent_at timestamptz not null default now(),
  unique (activity_id, due_date, reminder_time)
);

create index if not exists push_deliveries_user_id_idx on public.push_deliveries(user_id);
alter table public.push_deliveries enable row level security;
revoke all on table public.push_deliveries from anon, authenticated;
-- As entregas são consultadas/escritas apenas pela função agendada com service role.
