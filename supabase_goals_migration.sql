create table if not exists public.goals (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 title text not null check (char_length(title) between 1 and 160),
 description text,
 target_date date,
 target_value numeric(12,2) check (target_value is null or target_value > 0),
 current_value numeric(12,2) not null default 0 check (current_value >= 0),
 completed boolean not null default false,
 archived boolean not null default false,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create index if not exists goals_user_archived_created_idx on public.goals(user_id, archived, created_at desc);
alter table public.goals enable row level security;
revoke all on table public.goals from anon;
grant select, insert, update, delete on table public.goals to authenticated;
drop policy if exists "Users manage own goals" on public.goals;
create policy "Users manage own goals" on public.goals for all to authenticated
using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
