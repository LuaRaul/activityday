create table if not exists public.habits (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 120),
  frequency text not null default 'Diária' check (frequency in ('Diária', 'Semanal')),
  weekdays integer[] not null default '{}',
  archived boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint habits_weekdays_valid check (
    weekdays <@ array[0,1,2,3,4,5,6]::integer[]
  )
);

create index if not exists habits_user_active_idx
  on public.habits(user_id, archived, created_at desc);

create table if not exists public.habit_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  habit_id bigint not null references public.habits(id) on delete cascade,
  log_date date not null,
  completed boolean not null default false,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint habit_logs_one_per_day unique (habit_id, log_date)
);

create index if not exists habit_logs_user_date_idx
  on public.habit_logs(user_id, log_date desc);
create index if not exists habit_logs_habit_date_idx
  on public.habit_logs(habit_id, log_date desc);

alter table public.habits enable row level security;
alter table public.habit_logs enable row level security;

revoke all on table public.habits from anon;
revoke all on table public.habit_logs from anon;
grant select, insert, update, delete on table public.habits to authenticated;
grant select, insert, update, delete on table public.habit_logs to authenticated;
grant usage, select on sequence public.habits_id_seq to authenticated;
grant usage, select on sequence public.habit_logs_id_seq to authenticated;

drop policy if exists "Users manage own habits" on public.habits;
create policy "Users manage own habits" on public.habits
for all to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

drop policy if exists "Users manage own habit logs" on public.habit_logs;
create policy "Users manage own habit logs" on public.habit_logs
for all to authenticated
using ((select auth.uid()) = user_id)
with check (
  (select auth.uid()) = user_id
  and exists (
    select 1 from public.habits h
    where h.id = habit_id and h.user_id = (select auth.uid())
  )
);

create or replace function public.set_habit_updated_at()
returns trigger language plpgsql set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_habits_updated_at on public.habits;
create trigger set_habits_updated_at
before update on public.habits
for each row execute function public.set_habit_updated_at();

drop trigger if exists set_habit_logs_updated_at on public.habit_logs;
create trigger set_habit_logs_updated_at
before update on public.habit_logs
for each row execute function public.set_habit_updated_at();

-- Backstop de integridade: o log tem de pertencer ao mesmo utilizador do hábito.
create or replace function public.validate_habit_log_owner()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  if not exists (
    select 1 from public.habits h
    where h.id = new.habit_id and h.user_id = new.user_id
  ) then
    raise exception 'Habit log owner does not match habit owner';
  end if;
  return new;
end;
$$;

drop trigger if exists validate_habit_log_owner on public.habit_logs;
create trigger validate_habit_log_owner
before insert or update on public.habit_logs
for each row execute function public.validate_habit_log_owner();
